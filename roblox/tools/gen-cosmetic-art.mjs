// Weapon skin art for the game: compiles every skin designed in cosmetic-sheet.mjs with the SAME
// compiler the weapons use, into src/shared/CosmeticArt.luau. A skin is its weapon's grid with a new
// palette and inks, so it paints exactly the weapon's cells (tests/cosmetics.luau holds the footprint;
// the rectangles can split differently, since the compiler merges same-coloured cells). Paired weapons (DualWield) also get their one-of-a-pair unit, skinned. Run by hand
// after changing a skin:   node tools/gen-cosmetic-art.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { WEB, SINGLE_GRIDS } from './roblox-grids.mjs';
import { SKINS, skinGrid } from './cosmetic-sheet.mjs';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const { compile, compileAwakened } = await import(`${WEB}/weaponArt.js`);
const rects = (list) => `{\n${list.map((r) => `\t\t\t\t{ ${r.map((x) => (typeof x === 'string' ? `"${x}"` : String(x))).join(', ')} },`).join('\n')}\n\t\t\t}`;
const pal = (p) => `{ ${Object.entries(p).map(([k, v]) => `${k} = "${v}"`).join(', ')} }`;
const out = [];
for (const s of SKINS) {
  const g = skinGrid(s);
  const fields = [`\t\tweapon = "${s.weapon}",`, `\t\tpalette = ${pal(s.palette)},`,
    `\t\tsprites = ${rects(compile(g, s.palette))},`, `\t\tawakened = ${rects(compileAwakened(g, s.palette))},`];
  const unit = SINGLE_GRIDS[s.weapon];
  if (unit) {
    const ug = { ...unit, ink: { ...unit.ink, ...(s.ink || {}) } };
    fields.push(`\t\tsingle = ${rects(compile(ug, s.palette))},`, `\t\tsingleAwakened = ${rects(compileAwakened(ug, s.palette))},`);
  }
  out.push(`\t${s.id} = {\n${fields.join('\n')}\n\t},`);
}
fs.writeFileSync(path.join(HERE, '../src/shared/CosmeticArt.luau'), `--!nocheck
-- GENERATED by roblox/tools/gen-cosmetic-art.mjs from the skins in tools/cosmetic-sheet.mjs: each
-- weapon skin's art, in the rectangle format of Data/Art.luau, and the palette its trails and glow use.
-- Not regenerated by check.sh: re-run the tool after changing a skin.
return {
${out.join('\n')}
}
`);
console.log(`CosmeticArt.luau: ${SKINS.length} skins`);
