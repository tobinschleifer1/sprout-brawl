// Roblox-only weapon art: compiles the pixel grids of weapons that exist only in the Roblox build
// (src/shared/RobloxWeapons.luau) with the SAME compiler the generated art uses
// (web/src/data/weaponArt.js compile / compileAwakened), into src/shared/RobloxArt.luau.
//
// weaponArt.js already holds the Chakram's grid but only exports art for weapons the web has, so the
// grid is read out of its source. Weapons it has no grid for keep theirs here (LOCAL_GRIDS). Run by hand after changing a grid or a palette:
//   node tools/gen-roblox-art.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const WEB = path.join(HERE, '../../web/src/data');
const { compile, compileAwakened } = await import(`${WEB}/weaponArt.js`);

// Roblox-only weapons and their palettes (must match RobloxWeapons.luau)
const WEAPONS = {
  Chakram: { primary: '#C0C8D4', secondary: '#1E4A4A', tertiary: '#0F2626', accent: '#F4E8C0', glow: '#3CE8C8' },
  RocketBoots: { primary: '#D76B32', secondary: '#465366', tertiary: '#17212D', accent: '#FFE3AF', glow: '#62E8FF' },
};
const G = (ox, oy, rows, ink = {}) => ({ ox, oy, rows, ink });
// Grids for weapons weaponArt.js has none for (the web is left as it is): one boot, ankle-anchored,
// drawn once on each foot (GPT-6-Astra's design).
const LOCAL_GRIDS = {
  RocketBoots: G(4, 8, [
    '..TTTTTT......',
    '..TAAAAT......',
    '..TPPPST......',
    '..TPGGST......',
    '.TSPGGST......',
    '.TSPPPST......',
    '.TSPPPPTTT....',
    '.TSSPPPPPATT..',
    '.TTSSSSSSSST..',
    '..TTTTTTTTTT..',
  ]),
};
// One of a pair, for weapons held one in each hand (src/client/DualWield.luau). The web's grids
// draw the pair as one picture in one hand; these are the single unit each hand holds. A weapon
// whose grid is already one unit (Blasters, Gauntlets) needs none: each hand draws its grid.
// Reach is kept: the dagger's tip is as far ahead of its grip as the pair's front blade (11 px).
const SINGLE_GRIDS = {
  Daggers: G(4, 3, [
    '..............AC',
    '.....SS.....AAPq',
    '.....SS.ACCCcPS.',
    'eTjTjGGASSSSSS..',
    '.TTTTSS.........',
    '.....SS.........',
  ], { c: '#FF4A6A', C: '#FFB0BE', q: '#8A1A30', e: '#A0ACBE', j: '#4A3A5A' }),
  Chakram: G(4, 4, [
    '..PPPPP..',
    '.PPGGGPP.',
    'PPG...GPP',
    'PG.....GP',
    'PG.....GP',
    'PG.....GP',
    'PPG...GPP',
    '.PPGGGPP.',
    '..PPPPP..',
  ]),
};
const { WEAPON_BY_ID } = await import(`${WEB}/weapons/index.js`);
const paletteOf = (id) => WEAPONS[id] || WEAPON_BY_ID[id].palette;
const src = fs.readFileSync(`${WEB}/weaponArt.js`, 'utf8');
const gridOf = (id) => {
  if (LOCAL_GRIDS[id]) return LOCAL_GRIDS[id];
  const m = src.match(new RegExp(`\\n  ${id}: (G\\([\\s\\S]*?\\]\\)),\\n`));
  if (!m) throw new Error(`no grid for ${id} in weaponArt.js`);
  return Function('G', `return ${m[1]}`)(G);
};
const emitRects = (rects) => `{\n${rects.map((r) => `\t\t\t{ ${r.map((x) => (typeof x === 'string' ? `"${x}"` : String(x))).join(', ')} },`).join('\n')}\n\t\t}`;
const sprites = [], awakened = [];
for (const [id, pal] of Object.entries(WEAPONS)) {
  const g = gridOf(id);
  sprites.push(`\t\t${id} = ${emitRects(compile(g, pal))},`);
  awakened.push(`\t\t${id} = ${emitRects(compileAwakened(g, pal))},`);
}
const single = [], singleAwakened = [];
for (const [id, g] of Object.entries(SINGLE_GRIDS)) {
  single.push(`\t\t${id} = ${emitRects(compile(g, paletteOf(id)))},`);
  singleAwakened.push(`\t\t${id} = ${emitRects(compileAwakened(g, paletteOf(id)))},`);
}
const out = `--!nocheck
-- GENERATED by roblox/tools/gen-roblox-art.mjs from the grids in web/src/data/weaponArt.js - the art
-- of the Roblox-only weapons (RobloxWeapons.luau), in the same rectangle format as Data/Art.luau.
-- Not regenerated by check.sh: re-run the tool after changing a grid or a palette.
return {
\tsprites = {
${sprites.join('\n')}
\t},
\tawakened = {
${awakened.join('\n')}
\t},
\t-- one of a pair, per hand (DualWield.luau)
\tsingle = {
${single.join('\n')}
\t},
\tsingleAwakened = {
${singleAwakened.join('\n')}
\t},
}
`;
fs.writeFileSync(path.join(HERE, '../src/shared/RobloxArt.luau'), out);
console.log(`RobloxArt.luau: ${Object.keys(WEAPONS).join(', ')}`);
